import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { RECLAIM_PENDING_NEWS_SQL } from '../src/ingest/run-knowledge-document-sync.ts';
import {
  CLAIM_PENDING_DOCUMENTS_SQL,
  INSERT_CLAIM_EVIDENCE_SQL,
  INSERT_EVENT_EVIDENCE_SQL,
  MARK_DOCUMENT_EXTRACTED_SQL,
} from '../src/ingest/run-knowledge-extraction.ts';
import { RECENT_CLAIMS_SQL, RECENT_EVENTS_SQL } from '../src/publish/run-report-publish.ts';

const require = createRequire(new URL('../package.json', import.meta.url));
const { Client } = require('pg');
const pgpass = require(
  fileURLToPath(new URL('../../pgpass/lib/index.js', pathToFileURL(require.resolve('pg')))),
);
const adminUrl = new URL(process.env.KNOWLEDGE_REHEARSAL_ADMIN_DATABASE_URL ?? '');
if (
  !['postgres:', 'postgresql:'].includes(adminUrl.protocol) ||
  adminUrl.search !== '' ||
  adminUrl.hash !== ''
) {
  throw new Error('knowledge rehearsal admin URL must be a query-free PostgreSQL URL');
}

const databaseName = `stock_insight_knowledge_rehearsal_${randomBytes(5).toString('hex')}`;
if (!/^stock_insight_knowledge_rehearsal_[a-f0-9]+$/.test(databaseName)) {
  throw new Error('unsafe knowledge rehearsal database name');
}
const quotedDatabase = `"${databaseName}"`;
const rehearsalPassword = await new Promise((resolve, reject) => {
  pgpass(
    {
      host: adminUrl.hostname,
      port: Number(adminUrl.port || '5432'),
      database: decodeURIComponent(adminUrl.pathname.slice(1)),
      user: decodeURIComponent(adminUrl.username),
    },
    (password) => {
      if (typeof password !== 'string')
        reject(new Error('knowledge rehearsal pgpass credential missing'));
      else resolve(password);
    },
  );
});
const baseConnection = {
  host: adminUrl.hostname,
  port: Number(adminUrl.port || '5432'),
  user: decodeURIComponent(adminUrl.username),
  password: rehearsalPassword,
  connectionTimeoutMillis: 10_000,
};
const admin = new Client({
  ...baseConnection,
  database: decodeURIComponent(adminUrl.pathname.slice(1)),
});
await admin.connect();

let target;
let writer;
let result;
let primaryError;
const cleanupErrors = [];
const progress = (stage) => {
  if (process.env.KNOWLEDGE_REHEARSAL_PROGRESS === '1') {
    console.error(`[knowledge-rehearsal] ${stage}`);
  }
};

async function readReport(client, asOf) {
  const [events, claims] = await Promise.all([
    client.query(RECENT_EVENTS_SQL, [asOf, 50]),
    client.query(RECENT_CLAIMS_SQL, [asOf, 50]),
  ]);
  return {
    eventIds: events.rows.map((row) => Number(row.event_id)).sort((a, b) => a - b),
    claimIds: claims.rows.map((row) => Number(row.claim_id)).sort((a, b) => a - b),
  };
}

try {
  progress('before-create');
  await admin.query(`CREATE DATABASE ${quotedDatabase} TEMPLATE template0`);
  progress('after-create');
  target = new Client({ ...baseConnection, database: databaseName });
  writer = new Client({ ...baseConnection, database: databaseName });
  await target.connect();
  progress('after-target-connect');
  await writer.connect();
  progress('after-writer-connect');

  const connected = await target.query('SELECT current_database() AS database_name');
  assert.equal(connected.rows[0]?.database_name, databaseName);

  await target.query(`
    CREATE SCHEMA core;
    CREATE SCHEMA knowledge;

    CREATE TABLE core.entity (
      entity_id BIGINT PRIMARY KEY,
      canonical_name TEXT NOT NULL
    );

    CREATE TABLE knowledge.document (
      document_id BIGINT PRIMARY KEY,
      title TEXT NOT NULL,
      canonical_url TEXT NOT NULL,
      source_type TEXT NOT NULL,
      processing_status TEXT NOT NULL,
      legacy_source_document_pk BIGINT,
      metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
      published_at TIMESTAMPTZ,
      observed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
      available_at TIMESTAMPTZ NOT NULL
    );

    CREATE TABLE knowledge.document_chunk (
      chunk_id BIGINT PRIMARY KEY,
      document_id BIGINT NOT NULL,
      chunk_index INTEGER NOT NULL,
      content TEXT NOT NULL,
      revision_no INTEGER NOT NULL,
      ingested_at TIMESTAMPTZ NOT NULL,
      available_at TIMESTAMPTZ NOT NULL
    );

    CREATE TABLE knowledge.event (
      event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_type TEXT NOT NULL,
      summary_text TEXT NOT NULL,
      occurred_at TIMESTAMPTZ,
      verification_status TEXT NOT NULL,
      source_document_id BIGINT,
      target_entity_id BIGINT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
    );

    CREATE TABLE knowledge.event_evidence (
      event_id BIGINT NOT NULL,
      document_id BIGINT NOT NULL,
      chunk_id BIGINT NOT NULL,
      quote TEXT NOT NULL,
      evidence_role TEXT NOT NULL,
      source_weight DOUBLE PRECISION,
      PRIMARY KEY (event_id, document_id)
    );

    CREATE TABLE knowledge.claim (
      claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      subject_entity_id BIGINT NOT NULL,
      predicate TEXT NOT NULL,
      object_value JSONB NOT NULL,
      claim_type TEXT NOT NULL,
      extraction_confidence DOUBLE PRECISION NOT NULL,
      observed_at TIMESTAMPTZ NOT NULL,
      verification_status TEXT NOT NULL
    );

    CREATE TABLE knowledge.claim_evidence (
      claim_id BIGINT NOT NULL,
      document_id BIGINT NOT NULL,
      chunk_id BIGINT NOT NULL,
      quote TEXT NOT NULL,
      PRIMARY KEY (claim_id, document_id)
    );

    INSERT INTO core.entity VALUES (1, '검증 기업');
    INSERT INTO knowledge.document
      (document_id, title, canonical_url, source_type, processing_status, metadata, available_at)
    VALUES
      (1, 'Revision rehearsal', 'https://example.invalid/revision', 'news', 'extracted',
       '{"revision_no":"1"}'::jsonb, '2026-07-27T08:00:00Z');
    INSERT INTO knowledge.document_chunk
      (chunk_id, document_id, chunk_index, content, revision_no, ingested_at, available_at)
    VALUES
      (101, 1, 0, 'revision one verified quote', 1,
       '2026-07-27T08:00:00Z', '2026-07-27T08:00:00Z');
    INSERT INTO knowledge.event
      (event_id, event_type, summary_text, occurred_at, verification_status,
       source_document_id, target_entity_id, created_at)
    VALUES
      (201, 'earnings', 'revision one event', '2026-07-27T08:10:00Z', 'unverified',
       1, 1, '2026-07-27T08:11:00Z');
    INSERT INTO knowledge.claim
      (claim_id, subject_entity_id, predicate, object_value, claim_type,
       extraction_confidence, observed_at, verification_status)
    VALUES
      (301, 1, 'ANNOUNCED', '"revision one"'::jsonb, 'reported_claim',
       0.9, '2026-07-27T08:10:00Z', 'unverified');
  `);

  const failedRunId = 'knowledge-sync-run-a-rehearsal';
  const recoveryRunId = 'knowledge-sync-run-b-rehearsal';
  const staleExtractorId = 'knowledge-extraction-run-a-rehearsal';
  const currentExtractorId = 'knowledge-extraction-run-b-rehearsal';
  await target.query(
    `INSERT INTO knowledge.document
       (document_id, title, canonical_url, source_type, processing_status,
        legacy_source_document_pk, metadata, published_at, observed_at, available_at)
     VALUES
       (2, 'Failed run pending document', 'https://example.invalid/pending', 'news', 'pending',
        2002, jsonb_build_object(
          'revision_no', '1',
          'knowledge_sync_run_id', $1::text,
          'promoted_by', 'runtime-knowledge-sync-v1',
          'source_system', 'rss_news'
        ), '2026-07-27T08:05:00Z', '2026-07-27T08:05:00Z', '2026-07-27T08:05:00Z')`,
    [failedRunId],
  );
  const staleClaim = await target.query(CLAIM_PENDING_DOCUMENTS_SQL, [
    1,
    failedRunId,
    staleExtractorId,
    0,
  ]);
  await target.query("SELECT set_config('stock_insight.knowledge_sync_run_id',$1,false)", [
    recoveryRunId,
  ]);
  const reclaimed = await target.query(RECLAIM_PENDING_NEWS_SQL);
  const reclaimedDocument = await target.query(
    `SELECT metadata ->> 'knowledge_sync_run_id' AS run_id,
            metadata -> 'knowledge_sync_reclaim_history' AS history
       FROM knowledge.document
      WHERE document_id=2`,
  );
  const reclaimHistory = reclaimedDocument.rows[0]?.history;
  const failedRunPendingReclaimed =
    staleClaim.rowCount === 1 &&
    reclaimed.rowCount === 1 &&
    reclaimedDocument.rows[0]?.run_id === recoveryRunId &&
    Array.isArray(reclaimHistory) &&
    reclaimHistory.length === 1 &&
    reclaimHistory[0]?.from_run_id === failedRunId &&
    reclaimHistory[0]?.to_run_id === recoveryRunId;
  assert.equal(failedRunPendingReclaimed, true);

  const duplicateReclaim = await target.query(RECLAIM_PENDING_NEWS_SQL);
  const reclaimIdempotent = duplicateReclaim.rowCount === 0;
  assert.equal(reclaimIdempotent, true);
  const currentClaim = await target.query(CLAIM_PENDING_DOCUMENTS_SQL, [
    1,
    recoveryRunId,
    currentExtractorId,
    600,
  ]);
  assert.equal(currentClaim.rowCount, 1);
  const staleTerminal = await target.query(MARK_DOCUMENT_EXTRACTED_SQL, [
    2,
    staleExtractorId,
    failedRunId,
    1,
  ]);
  const staleExtractorRejected = staleTerminal.rowCount === 0;
  assert.equal(staleExtractorRejected, true);
  const currentTerminal = await target.query(MARK_DOCUMENT_EXTRACTED_SQL, [
    2,
    currentExtractorId,
    recoveryRunId,
    1,
  ]);
  const currentExtractorCompleted = currentTerminal.rowCount === 1;
  assert.equal(currentExtractorCompleted, true);
  const recoveryBacklog = await target.query(
    `SELECT count(*)::int AS count
       FROM knowledge.document
      WHERE processing_status IN ('pending','chunked')
        AND source_type='news'
        AND metadata ->> 'knowledge_sync_run_id'=$1`,
    [recoveryRunId],
  );
  const reclaimedBacklogDrained = recoveryBacklog.rows[0]?.count === 0;
  assert.equal(reclaimedBacklogDrained, true);

  const eventOneBinding = await target.query(INSERT_EVENT_EVIDENCE_SQL, [
    201,
    1,
    'revision one verified quote',
    1,
  ]);
  const claimOneBinding = await target.query(INSERT_CLAIM_EVIDENCE_SQL, [
    301,
    1,
    'revision one verified quote',
    1,
  ]);
  assert.deepEqual(eventOneBinding.rows[0], {
    expected_chunk_id: '101',
    bound_chunk_id: '101',
  });
  assert.deepEqual(claimOneBinding.rows[0], {
    expected_chunk_id: '101',
    bound_chunk_id: '101',
  });

  const asOf = '2026-07-27T09:00:00Z';
  const revisionOneVisible = await readReport(target, asOf);
  assert.deepEqual(revisionOneVisible, { eventIds: [201], claimIds: [301] });

  await target.query(`
    UPDATE knowledge.document
       SET processing_status='pending', metadata='{"revision_no":"2"}'::jsonb
     WHERE document_id=1;
    INSERT INTO knowledge.document_chunk
      (chunk_id, document_id, chunk_index, content, revision_no, ingested_at, available_at)
    VALUES
      (102, 1, 0, 'revision two verified quote', 2,
       '2026-07-27T08:30:00Z', '2026-07-27T08:30:00Z');
  `);
  const whilePending = await readReport(target, asOf);
  const revisionOneExcluded =
    whilePending.eventIds.length === 0 && whilePending.claimIds.length === 0;
  assert.equal(revisionOneExcluded, true);

  await target.query(`
    UPDATE knowledge.document SET processing_status='extracted' WHERE document_id=1;
    INSERT INTO knowledge.event
      (event_id, event_type, summary_text, occurred_at, verification_status,
       source_document_id, target_entity_id, created_at)
    VALUES
      (202, 'earnings', 'revision two event', '2026-07-27T08:30:00Z', 'unverified',
       1, 1, '2026-07-27T08:31:00Z');
    INSERT INTO knowledge.claim
      (claim_id, subject_entity_id, predicate, object_value, claim_type,
       extraction_confidence, observed_at, verification_status)
    VALUES
      (302, 1, 'ANNOUNCED', '"revision two"'::jsonb, 'reported_claim',
       0.9, '2026-07-27T08:30:00Z', 'unverified');
  `);
  const eventTwoBinding = await target.query(INSERT_EVENT_EVIDENCE_SQL, [
    202,
    1,
    'revision two verified quote',
    2,
  ]);
  const claimTwoBinding = await target.query(INSERT_CLAIM_EVIDENCE_SQL, [
    302,
    1,
    'revision two verified quote',
    2,
  ]);
  assert.equal(String(eventTwoBinding.rows[0]?.expected_chunk_id), '102');
  assert.equal(String(eventTwoBinding.rows[0]?.bound_chunk_id), '102');
  assert.equal(String(claimTwoBinding.rows[0]?.expected_chunk_id), '102');
  assert.equal(String(claimTwoBinding.rows[0]?.bound_chunk_id), '102');

  const revisionTwoVisible = await readReport(target, asOf);
  assert.deepEqual(revisionTwoVisible, { eventIds: [202], claimIds: [302] });

  await target.query(`
    INSERT INTO knowledge.event
      (event_id, event_type, summary_text, occurred_at, verification_status,
       source_document_id, target_entity_id, created_at)
    VALUES
      (203, 'earnings', 'conflicting evidence event', '2026-07-27T08:35:00Z', 'unverified',
       1, 1, '2026-07-27T08:36:00Z'),
      (204, 'earnings', 'orphan candidate event', '2026-07-27T08:36:00Z', 'unverified',
       1, 1, '2026-07-27T08:37:00Z');
    INSERT INTO knowledge.event_evidence
      (event_id, document_id, chunk_id, quote, evidence_role, source_weight)
    VALUES
      (203, 1, 101, 'revision one verified quote', 'support', NULL);
  `);
  const conflict = await target.query(INSERT_EVENT_EVIDENCE_SQL, [
    203,
    1,
    'revision two verified quote',
    2,
  ]);
  const conflictingBindingRejected =
    String(conflict.rows[0]?.expected_chunk_id) !== String(conflict.rows[0]?.bound_chunk_id);
  assert.equal(conflictingBindingRejected, true);

  const orphanAttempt = await target.query(INSERT_EVENT_EVIDENCE_SQL, [
    204,
    1,
    'quote absent from every current chunk',
    2,
  ]);
  const orphanCount = await target.query(
    'SELECT count(*)::int AS count FROM knowledge.event_evidence WHERE event_id=204',
  );
  const orphanBlocked = orphanAttempt.rowCount === 0 && orphanCount.rows[0]?.count === 0;
  assert.equal(orphanBlocked, true);

  await target.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY');
  await target.query('SELECT 1');
  const beforeLateWrite = await readReport(target, asOf);
  await writer.query(`
    INSERT INTO knowledge.event
      (event_id, event_type, summary_text, occurred_at, verification_status,
       source_document_id, target_entity_id, created_at)
    VALUES
      (205, 'earnings', 'late event', '2026-07-27T08:50:00Z', 'unverified',
       1, 1, '2026-07-27T08:51:00Z');
    INSERT INTO knowledge.claim
      (claim_id, subject_entity_id, predicate, object_value, claim_type,
       extraction_confidence, observed_at, verification_status)
    VALUES
      (305, 1, 'ANNOUNCED', '"late claim"'::jsonb, 'reported_claim',
       0.9, '2026-07-27T08:50:00Z', 'unverified');
  `);
  await writer.query(INSERT_EVENT_EVIDENCE_SQL, [205, 1, 'revision two verified quote', 2]);
  await writer.query(INSERT_CLAIM_EVIDENCE_SQL, [305, 1, 'revision two verified quote', 2]);
  const duringSameSnapshot = await readReport(target, asOf);
  await target.query('COMMIT');
  const afterNewSnapshot = await readReport(target, asOf);

  const lateWriteInvisible =
    JSON.stringify(beforeLateWrite) === JSON.stringify(duringSameSnapshot) &&
    !duringSameSnapshot.eventIds.includes(205) &&
    !duringSameSnapshot.claimIds.includes(305) &&
    afterNewSnapshot.eventIds.includes(205) &&
    afterNewSnapshot.claimIds.includes(305);
  assert.equal(lateWriteInvisible, true);
  progress('after-invariants');

  result = {
    ok: true,
    connectedDatabaseVerified: true,
    revisionOneExcluded,
    revisionTwoOnly:
      JSON.stringify(revisionTwoVisible) === JSON.stringify({ eventIds: [202], claimIds: [302] }),
    orphanBlocked,
    conflictingBindingRejected,
    lateWriteInvisible,
    failedRunPendingReclaimed,
    reclaimIdempotent,
    reclaimedBacklogDrained,
    staleExtractorRejected,
    currentExtractorCompleted,
    cleanupVerified: false,
  };
} catch (error) {
  primaryError = error;
} finally {
  for (const client of [target, writer]) {
    if (!client) continue;
    try {
      await client.query('ROLLBACK');
    } catch {}
    try {
      await client.end();
    } catch (error) {
      cleanupErrors.push(error);
    }
  }
  progress('after-client-end');
  try {
    await admin.query(
      'SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname=$1 AND pid<>pg_backend_pid()',
      [databaseName],
    );
    progress('before-drop');
    await admin.query(`DROP DATABASE IF EXISTS ${quotedDatabase} WITH (FORCE)`);
    progress('after-drop');
    const absence = await admin.query(
      'SELECT count(*)::int AS count FROM pg_database WHERE datname=$1',
      [databaseName],
    );
    if (absence.rows[0]?.count !== 0) {
      cleanupErrors.push(new Error('knowledge rehearsal database cleanup failed'));
    } else if (result) {
      result.cleanupVerified = true;
    }
  } catch (error) {
    cleanupErrors.push(error);
  }
  try {
    await admin.end();
    progress('after-admin-end');
  } catch (error) {
    cleanupErrors.push(error);
  }
}

const failures = primaryError ? [primaryError, ...cleanupErrors] : cleanupErrors;
if (failures.length > 0) {
  throw new AggregateError(failures, 'knowledge revision rehearsal or cleanup failed');
}
if (!result?.ok || !Object.values(result).every(Boolean)) {
  throw new Error(`knowledge revision rehearsal invariant failed: ${JSON.stringify(result)}`);
}
console.log(JSON.stringify(result));
